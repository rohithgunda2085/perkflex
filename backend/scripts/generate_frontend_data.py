"""Writes frontend/src/rules/data.ts from backend/app/rules/data.py, so the screens show the same fares, airports and
reward values the API uses. Run after changing backend/app/rules/data.py:

    cd backend && ../../.venv/bin/python scripts/generate_frontend_data.py

tests/test_frontend_data.py fails if the committed file is out of date.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.rules import data  # noqa: E402

OUTPUT = Path(__file__).resolve().parents[2] / "frontend" / "src" / "rules" / "data.ts"


def render() -> str:
    fares = [
        {
            "id": f.id,
            "name": f.name,
            "price": f.price,
            "bags": f.bags,
            "seat": f.seat,
            "refundable": f.refundable,
            "multiplier": f.multiplier,
            "description": f.description,
        }
        for f in data.FARES
    ]
    flights = [
        {"id": f.id, "departure": f.departure, "arrival": f.arrival, "duration": f.duration, "offset": f.offset}
        for f in data.FLIGHTS
    ]
    airports = [{"code": a.code, "city": a.city} for a in data.AIRPORTS]
    rules = {
        "tax": data.TAX_CENTS / 100,
        "seatCash": data.SEAT_CASH,
        "bagCash": list(data.BAG_CASH),
        "release": data.RELEASE_POINTS,
        "redeem": data.REDEEM_POINTS,
    }

    def js(value) -> str:
        return json.dumps(value, indent=2, ensure_ascii=False)

    return f"""// GENERATED by backend/scripts/generate_frontend_data.py from backend/app/rules/data.py. Do not edit by hand.
// Display constants only: the API does all pricing.
import type {{ Fare, FareId, SeatClass }} from "./types.ts";

export const FARES: Fare[] = {js(fares)};

export const FLIGHTS: {{ id: string; departure: string; arrival: string; duration: string; offset: number }}[] = {js(flights)};

export const AIRPORTS: {{ code: string; city: string }}[] = {js(airports)};

export const RULES = {js(rules)} as const;

export const SEAT_NAMES: Record<SeatClass, string> = {js(dict(data.SEAT_NAMES))};

export const SEAT_ORDER: SeatClass[] = {js(list(data.SEAT_ORDER))};

export const fmt = (value: number) => new Intl.NumberFormat("en-US").format(value);
export const money = (value: number) =>
  new Intl.NumberFormat("en-US", {{
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 2,
    minimumFractionDigits: 2,
  }}).format(value);
export const fareById = (id: FareId) => FARES.find((f) => f.id === id)!;
export const flightById = (id: string) => FLIGHTS.find((f) => f.id === id)!;
"""


if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(OUTPUT.parents[3])}")
